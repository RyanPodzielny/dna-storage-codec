"""
Huffman Coding implementation for data compression. Includes classes for standard Huffman encoding and a quaternary 
version that uses DNA bases (A, C, G, T) for encoding. 

This module provides classes and methods to perform Huffman coding, a lossless data compression algorithm. It includes 
functionality for building a Huffman tree, generating Huffman codes, encoding data, and decoding encoded data. It is
purely a theoretical implementation, storing the Huffman table and encoded data in a simple string format, and should
be stored differently in a real application.
"""

from typing import override
from Encoding import Encoding
from PriorityQueue import PriorityQueue


class Huffman(Encoding):
    def __init__(self) -> None:
        """
        Initializes the Huffman coding class with an empty priority queue and a separator for encoding and decoding.
        """
        super().__init__()

        self.priority_queue: PriorityQueue = PriorityQueue()

        # Default multiplier for binary encoding (1 bit per symbol)
        self.bit_multiplier = 1  
        

    def count_frequencies(self, data: str) -> dict[str, int]:
        """
        Counts the frequency of each character in the input data.
        
        Returns:
            A dictionary mapping each character to its frequency in the input data.
        """
        # Count the frequency of each character in the input data
        frequencies: dict[str, int] = {}
        for char in data:
            if char in frequencies:
                frequencies[char] += 1
            else:
                frequencies[char] = 1
        
        return frequencies


    def build_tree(self, data: str) -> None:
        """
        Builds the Huffman tree based on the character frequencies in the input data.

        Uses a min heap priority queue to build the tree by merging the two smallest frequency nodes until only one node 
        remains, which becomes the root of the tree.

        Args:
            data: The input data for which the Huffman tree is to be built.

        Raises:
            ValueError: If the input data is empty.
        """

        # Set up our priority queue with the frequencies
        self.priority_queue.build_queue(self.count_frequencies(data))

        # Our children
        left: tuple
        right: tuple

        # Merged values
        merged_frequency: int
        merged_node: tuple

        # While there is more than one node in the priority queue, we need to merge nodes
        while self.priority_queue.size > 1:
            # Dequeue the two nodes with the smallest frequencies
            left = self.priority_queue.dequeue()
            right = self.priority_queue.dequeue()

            # Create a new internal node with these two nodes as children
            merged_frequency = left[0] + right[0]
            merged_node = (merged_frequency, (left, right))

            # Enqueue the new node back into the priority queue
            self.priority_queue.enqueue(merged_node)


    def generate_codes(self) -> dict[str, str]:
        """
        Generates the Huffman codes for each character based on the constructed Huffman tree.

        Left edges are assigned '0' and right edges are assigned '1'. The codes are generated by traversing the tree
        from the root to each leaf node.

        Returns:
            A dictionary mapping each character to its corresponding Huffman code.

        Raises:
            ValueError: If the priority queue does not contain exactly one node (the root of the Huffman tree).
        """

        # Ensure we only have one node left
        if self.priority_queue.get_size() != 1:
            raise ValueError("Priority queue should have exactly one node left to generate codes.")

        # Initialize an empty dictionary to hold the codes
        codes: dict[str, str] = {}

        # Helper function to recursively generate codes
        def _create_code(node: tuple, current_code: str="") -> None:
            # If we have a string it is a leaf, otherwise it is an internal node
            if isinstance(node[1], str):  # Leaf node
                codes[node[1]] = current_code
                return

            # Internal node, traverse left and right
            _create_code(node[1][0], current_code + '0')  # Left child
            _create_code(node[1][1], current_code + '1')  # Right child

        # Start the recursive code generation from the root node
        root_node = self.priority_queue.top()
        _create_code(root_node)

        return codes
    

    def encode(self, data: str) -> tuple[dict[str, str], str]:
        """
        Encodes the given data using the generated Huffman codes.

        Args:
            data: The string to be encoded.

        Returns:
            A tuple containing the Huffman codes and the encoded data.
        """

        # Build tree and generate Huffman codes
        self.build_tree(data)
        huffman_codes: dict[str, str] = self.generate_codes()
        encoded_data: str = "".join(huffman_codes[char] for char in data)

        # Return the table and encoded data as or string of encoded data
        return huffman_codes, encoded_data


    def encode_from_file(self, in_path: str, out_path: str) -> str:
        """
        Encodes the data from the input file and writes the encoded data and Huffman table to the output file.

        Args:
            in_path: Path to the input file containing the data to be encoded.
            out_path: Path to the output file where the encoded data and Huffman table will be written.

        Returns:
            The encoded data as a string.

        Raises:
            FileNotFoundError: If the input file does not exist.
        """
        # Open the input file and read the data
        with open(in_path, 'r', encoding='utf-8', errors='ignore') as f:
            data: str = f.read()
        
        # Get the Huffman codes and encoded data
        huffman_codes, encoded_data = self.encode(data)

        # Record the separator to separate the table and encoded data
        # Note: This is a theoretical implementation and purely used to showcase the concep
        output: str = encoded_data + "\n" + self.SEPARATOR
        # Then the table
        output += "\n".join(f"{char}:{code}" for char, code in huffman_codes.items())

        # Write the table and encoded data to the output file
        with open(out_path, 'w') as f:
            f.write(output)

        return output


    def format_table(self, raw_table: str) -> dict[str, str]:
        """
        Formats the raw Huffman table string into a dictionary mapping codes to characters.

        Args:
            raw_table: The raw Huffman table string read from the encoded file.

        Returns:
            A dictionary mapping Huffman codes to their corresponding characters.
        """

        # Initialize an empty dictionary to hold the formatted table
        huffman_codes: dict[str, str] = {}

        # Remove any trailing whitespace or newlines
        raw_table.rstrip()

        char: str
        code: str

        is_newline: bool = False
        # Need to keep track of newline characters
        for line in raw_table.splitlines():
            # Empty line means we split on newline
            if line == "":
                is_newline = True
                continue

            char, code = line[0], line[2:]  

            # Ensure we record the newline character when found
            if is_newline:
                char = "\n"
                # Skip the first character which is the newline
                code = line[1:]  
                is_newline = False

            if char is None or code is None:
                raise ValueError("Invalid Huffman table format. Each line should be in the format 'char:code'.")

            huffman_codes[code] = char

        return huffman_codes


    def decode(self,  encoded_data: str, huffman_codes: dict[str, str]) -> str:
        """
        Decodes the encoded data using the provided Huffman codes.

        Args:
            encoded_data: The encoded data to be decoded.
            huffman_codes: A dictionary mapping Huffman codes to their corresponding characters.

        Returns:
            The decoded data as a string.
        """
        # Decode the encoded data
        decoded_data: str = ""
        current_code: str = ""

        # For all our bits, try to match them to a code, match = append and reset
        for bit in encoded_data:
            current_code += bit

            # If match found, append and reset current_code
            if current_code in huffman_codes:
                decoded_data += huffman_codes[current_code]
                current_code = ""

        return decoded_data


    def decode_to_file(self, in_path: str, out_path: str) -> str:
        """
        Decodes the encoded data from a file and writes the result to another file.

        Args:
            in_path: The path to the input file containing the encoded data.
            out_path: The path to the output file where the decoded data will be written.

        Returns:
            The decoded data as a string.

        Raises:
            FileNotFoundError: If the input file does not exist.
            ValueError: If the input file format is invalid or if the Huffman table cannot be parsed.
        """
        # Parse encoded data and table from the input file
        with open(in_path, 'r', encoding='utf-8', errors='ignore') as f:
            data: str = f.read().strip()

        # Split the data into the table and encoded data
        values: list[str] = data.split(self.SEPARATOR)
        if len(values) < 2:
            raise ValueError("Invalid input format. Expected a separator between table and encoded data.")

        # Enocoded data is first
        encoded_data: str = values[0]
        huffman_codes: dict[str, str] = self.format_table(values[1])

        # Now decode the data using the table
        decoded_data: str = self.decode(encoded_data, huffman_codes)
        with open(out_path, 'w', encoding='utf-8', errors='ignore') as f:
            f.write(decoded_data)

        return decoded_data


    def calculate_size(self, encoded_data: str) -> tuple[int, int]:
        """
        Calculates the size of the encoded data and table in bits.

        Args:
            encoded_data: The encoded data as a string of bits.

        Returns:
            A tuple of the size of the encoded data in bits and size of the table in bits.

        Raises:
            ValueError: If the encoded data is not a valid binary string.
        """
        # Split the encoded data and table
        values: list[str] = encoded_data.split(self.SEPARATOR)
        if len(values) != 2:
            raise ValueError("Invalid encoded data format. Expected a separator between table and encoded data.")

        # Calculate the size of the encoded data in bits
        encoded_bits = len(values[0]) * self.bit_multiplier

        # Calculate the size of the table in bits
        table_bits = 0
        huffman_codes: dict[str, str] = self.format_table(values[1])
        for _, code in huffman_codes.items():
            # Each character is stored as 8 bits (1 byte) and the code is stored as its length in bits
            table_bits += 8 + (len(code) * self.bit_multiplier)

        return encoded_bits, table_bits


class HuffmanQuaternary(Huffman):
    def __init__(self) -> None:
        """
        Initializes a new instance of the HuffmanQuaternary class.

        This class extends the Huffman class to implement a quaternary version of Huffman coding, which uses four
        symbols (A, C, G, T) instead of the traditional binary symbols (0, 1).
        """
        super().__init__()

        # Each DNA base represents 2 bits, so we set the bit multiplier accordingly
        self.bit_multiplier = 2  

        self.TREE_ORDER: tuple[str, ...] = ('A', 'C', 'G', 'T')


    @override
    def build_tree(self, data: str) -> None:
        """
        Builds the Huffman tree for the given data.

        Uses a min heap piriority queue like standard Huffman, but intead merges 4 children at a time instead of 2. This
        allows for a quaternary tree structure, which is more suitable for encoding data using four symbols 
        (A, C, G, T).

        Args:
            data: The input data to build the tree for.

        Raises:
            ValueError: If the input data is empty or if the Huffman tree cannot be built.
        """
        self.priority_queue.build_queue(self.count_frequencies(data))

        # Merged values
        merged_frequency: int = 0
        merged_node: tuple

        # We will have four children, so we need to merge four nodes at a time
        while self.priority_queue.size > 1:
            # Should have 4 children per
            children: list[tuple[int, str]] = []

            # Dequeue four nodes with smallest frequencies. If we don't have four, just take what we can
            for _ in range(4):
                if not self.priority_queue.is_empty():
                    children.append(self.priority_queue.dequeue())
                else:
                    break

            # Sum up the frequencies
            for child in children:
                merged_frequency += child[0]

            # Create a new internal node and put pack onto queue
            merged_node = (merged_frequency, tuple(children))

            self.priority_queue.enqueue(merged_node)


    @override
    def generate_codes(self) -> dict[str, str]:
        """
        Generates the Huffman codes for each DNA base pair on the constructed quaternary Huffman tree.

        Returns:
            A dictionary mapping each character to its corresponding Huffman code.

        Raises:
            ValueError: If the priority queue does not contain exactly one node (the root of the quaternary Huffman).
        """
        # Ensure we only have one node left
        if self.priority_queue.size != 1:
            raise ValueError("Priority queue should have exactly one node left to generate codes.")

        # Initialize an empty dictionary to hold the codes
        codes: dict[str, str] = {}

        # Helper function to recursively generate codes
        def _create_code(node: tuple, current_code: str="") -> None:
            # If we have a string it is a leaf, otherwise it is an internal node
            if isinstance(node[1], str):  # Leaf node
                codes[node[1]] = current_code
                return

            # Traverse the children, and append the proper DNA base based on the current child number
            for index, child in enumerate(node[1]):
                _create_code(child, current_code + self.TREE_ORDER[index]) 

            
        # Start the recursive code generation from the root node
        root_node = self.priority_queue.top()
        _create_code(root_node)

        return codes